#!/usr/bin/env node
// Bakes the three body OBJs in assets-src/ (one base mesh in three shapes: the same faces, vertices and UV indices) into
// src/game/present/dummy-bodies.ts: one shared triangle index and UV set, and each body's rest positions, base64-packed.
//
//   node scripts/bake-dummy-bodies.mjs
//
// The OBJs are in centimetres, y up, facing +z, in a T-pose. Positions are written in metres with each body's feet at y = 0;
// nothing else is changed (the pose and the bone weights are the dummy's own code's). Quads split along their 0-2 diagonal,
// keeping the OBJ's counter-clockwise (outward) winding.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const SOURCE = join(ROOT, "assets-src");
const OUT = join(ROOT, "src", "game", "present", "dummy-bodies.ts");
/** The OBJs' unit (cm) in metres. */
const CM = 0.01;
/** Position quantum (m): 0.1 mm, so ±3.2 m fits an Int16. */
const QUANTUM = 1e-4;
const BODIES = { slenderMan: "Slender_Man_Lores.obj", slenderWoman: "Slender_Woman_Lores.obj", obeseMan: "Obese_Man_Lores.obj" };

function parse(file) {
  const v = [];
  const vt = [];
  const faces = [];
  for (const line of readFileSync(join(SOURCE, file), "utf8").split("\n")) {
    const p = line.trim().split(/\s+/);
    if (p[0] === "v") v.push([+p[1], +p[2], +p[3]]);
    else if (p[0] === "vt") vt.push([+p[1], +p[2]]);
    else if (p[0] === "f") faces.push(p.slice(1).map((c) => c.split("/").map((n) => Number(n) - 1)));
  }
  return { v, vt, faces };
}

const parsed = Object.fromEntries(Object.entries(BODIES).map(([name, file]) => [name, parse(file)]));
const base = parsed.slenderMan;
const faceKey = (faces) => faces.map((f) => f.map((c) => `${c[0]}/${c[1]}`).join(" ")).join("\n");
for (const [name, body] of Object.entries(parsed)) {
  if (faceKey(body.faces) !== faceKey(base.faces)) throw new Error(`${name}: its faces are not the slender man's; the bodies must share one topology`);
}

// One output vertex per (position, uv) corner pair, in first-use order.
const corner = new Map();
const pairs = [];
const index = [];
const at = (c) => {
  const key = `${c[0]}/${c[1]}`;
  let k = corner.get(key);
  if (k === undefined) {
    k = pairs.length;
    corner.set(key, k);
    pairs.push(c);
  }
  return k;
};
for (const f of base.faces) {
  const k = f.map(at);
  for (let i = 1; i + 1 < k.length; i++) index.push(k[0], k[i], k[i + 1]);
}
if (pairs.length > 65535) throw new Error(`${pairs.length} vertices do not fit a Uint16 index`);

// One UV set: the slender man's (the woman's differs by at most 0.0125, a re-layout of the same islands).
const uv = new Uint16Array(pairs.length * 2);
for (const [k, [, t]] of pairs.entries()) {
  uv[k * 2] = Math.round(base.vt[t][0] * 65535);
  uv[k * 2 + 1] = Math.round(base.vt[t][1] * 65535);
}

const positions = {};
const report = [];
for (const [name, body] of Object.entries(parsed)) {
  const floor = Math.min(...body.v.map((p) => p[1])) * CM;
  const out = new Int16Array(pairs.length * 3);
  const min = [Infinity, Infinity, Infinity];
  const max = [-Infinity, -Infinity, -Infinity];
  for (const [k, [p]] of pairs.entries()) {
    const xyz = [body.v[p][0] * CM, body.v[p][1] * CM - floor, body.v[p][2] * CM];
    for (let i = 0; i < 3; i++) {
      out[k * 3 + i] = Math.round(xyz[i] / QUANTUM);
      min[i] = Math.min(min[i], xyz[i]);
      max[i] = Math.max(max[i], xyz[i]);
    }
  }
  positions[name] = out;
  report.push(`${name}: x ${min[0].toFixed(3)}..${max[0].toFixed(3)} y ${min[1].toFixed(3)}..${max[1].toFixed(3)} z ${min[2].toFixed(3)}..${max[2].toFixed(3)} m`);
}

const b64 = (typed) => Buffer.from(typed.buffer, typed.byteOffset, typed.byteLength).toString("base64");
const src = `// Generated by scripts/bake-dummy-bodies.mjs from assets-src/*.obj. Do not edit: re-run the script.
/**
 * The dummy's three body shapes (one base mesh: the same ${index.length / 3} triangles over ${pairs.length} vertices), at rest in the source's
 * T-pose, in metres, y up, facing +z, feet at y = 0. Positions are Int16 in units of \`BODY_QUANTUM\` m; UVs are Uint16 over [0, 1].
 */
export const BODY_VERTICES = ${pairs.length};
export const BODY_QUANTUM = ${QUANTUM};
const INDEX = "${b64(new Uint16Array(index))}";
const UV = "${b64(uv)}";
const POSITIONS = {
${Object.entries(positions).map(([name, p]) => `  ${name}: "${b64(p)}",`).join("\n")}
} as const;
export type BodyShape = keyof typeof POSITIONS;
export const BODY_SHAPES = Object.keys(POSITIONS) as BodyShape[];

const bytes = (base64: string): Uint8Array => Uint8Array.from(atob(base64), (c) => c.charCodeAt(0));

/** The shared triangle list (counter-clockwise outward). */
export function bodyIndex(): Uint16Array {
  return new Uint16Array(bytes(INDEX).buffer);
}

/** The shared UVs, two floats a vertex. */
export function bodyUv(): Float32Array {
  return Float32Array.from(new Uint16Array(bytes(UV).buffer), (u) => u / 65535);
}

/** Body \`shape\`'s rest positions (m), three floats a vertex. */
export function bodyPositions(shape: BodyShape): Float32Array {
  return Float32Array.from(new Int16Array(bytes(POSITIONS[shape]).buffer), (q) => q * BODY_QUANTUM);
}
`;
writeFileSync(OUT, src);
console.log(`${OUT}: ${index.length / 3} triangles, ${pairs.length} vertices, ${(src.length / 1024).toFixed(0)} KB`);
for (const line of report) console.log(line);
